  await expect(article.getByRole('button', { name: '신입 공개 채용 삭제', exact: true })).toBeFocused()
  await article.getByRole('button', { name: '신입 공개 채용 삭제', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: '삭제', exact: true }).click()
