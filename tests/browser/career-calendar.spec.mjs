  await expect(article.getByRole('button', { name: '신입 공개 채용 수정', exact: true })).toBeFocused()
  await expect(article.getByRole('link')).toHaveCount(1)
  await expect(article).toContainText('수정한 메모')
  await page.screenshot({ path: `test-results/career-detail-${width}.png`, fullPage: true })
