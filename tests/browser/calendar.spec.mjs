async function add(page, { date = '2026-12-31', title, note = false, time = '' }) {
  await page.goto(`/#/calendar/${date}`)
  await page.getByRole('button', { name: note ? '노트 추가' : '일정 추가', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: note ? '노트 추가' : '일정 추가' })
  await dialog.getByLabel(note ? '내용' : '제목', { exact: true }).fill(title)
  await dialog.getByLabel('날짜', { exact: true }).fill(date)
  if (time) await dialog.getByLabel('시간 (선택)', { exact: true }).fill(time)
  if (note) await expect(dialog.getByLabel('시간 (선택)', { exact: true })).toHaveCount(0)
  await dialog.getByRole('button', { name: '저장', exact: true }).click()
  await expect(dialog).toBeHidden()
}

test('월간 캘린더에서 날짜를 선택해 일정 빠르게 추가', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/#/calendar?month=2027-01')
  const addButton = page.getByRole('button', { name: '일정 추가', exact: true })
  await expect(addButton).toBeEnabled()
  await addButton.focus()
  await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog', { name: '일정 추가', exact: true })
  await expect(dialog.getByLabel('날짜', { exact: true })).toHaveValue('2027-01-01')
  await dialog.getByLabel('제목', { exact: true }).fill('빠르게 추가한 일정')
  await dialog.getByRole('button', { name: '날짜 달력 열기' }).click()
  await page.getByRole('button', { name: '2027년 1월 15일', exact: true }).click()
  await dialog.getByLabel('시간 (선택)', { exact: true }).fill('13:45')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await dialog.getByRole('button', { name: '저장', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(addButton).toBeFocused()
  await expect(page.getByRole('link', { name: '2027-01-15 상세 보기', exact: true })).toContainText('빠르게 추가한 일정')
  await expect(page.locator('[data-sonner-toast]')).toHaveCount(1)
  await page.reload()
  await page.getByRole('link', { name: '2027-01-15 상세 보기', exact: true }).click()
  await page.getByRole('button', { name: '빠르게 추가한 일정 수정·삭제', exact: true }).click()
  await expect(page.getByLabel('시간 (선택)', { exact: true })).toHaveValue('13:45')
})

test('간단한 시간 입력과 Enter 저장, 빈 시간은 종일로 저장', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/#/calendar/2026-12-31')
  for (const [raw, expected] of [['1', '01:00'], ['130', '01:30'], ['오후 1시', '13:00'], ['', '']]) {
    const title = `시간 확인 ${raw || '종일'}`
    await page.getByRole('button', { name: '일정 추가', exact: true }).click()
    await page.getByLabel('제목', { exact: true }).fill(title)
    const input = page.getByLabel('시간 (선택)', { exact: true })
    await input.fill(raw)
    await input.press('Enter')
    await expect(page.getByRole('dialog', { name: '일정 추가', exact: true })).toBeHidden()
    await page.reload()
    await page.getByRole('button', { name: `${title} 수정·삭제`, exact: true }).click()
    await expect(input).toHaveValue(expected)
    await page.getByRole('button', { name: '취소', exact: true }).click()
  }
  await page.getByRole('button', { name: '시간 확인 130 수정·삭제', exact: true }).click()
  await page.getByLabel('시간 (선택)', { exact: true }).fill('')
  await page.getByRole('button', { name: '저장', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: '시간 확인 130 수정·삭제', exact: true }).click()
  await expect(page.getByLabel('시간 (선택)', { exact: true })).toHaveValue('')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

