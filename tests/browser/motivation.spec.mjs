  await page.getByRole('button', { name: '저장', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('올바른 유튜브')
  await page.getByLabel('유튜브 주소').fill('https://youtu.be/M7lc1UVf-VE')
