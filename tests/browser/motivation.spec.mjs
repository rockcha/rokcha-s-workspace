  await page.getByRole('button', { name: '다시 시작하는 마음 재생', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('iframe')).toHaveAttribute('src', /youtube\.com\/embed\/M7lc1UVf-VE/)
  expect(new URL(await page.locator('iframe').getAttribute('src')).searchParams.get('origin')).toBe('http://127.0.0.1:4175')
