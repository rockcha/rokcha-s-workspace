  await expect(page.locator('article')).toContainText('어제보다 한 걸음 더.')
  await page.getByRole('button', { name: '영상 추가', exact: true }).click()
  await page.getByLabel('유튜브 주소').fill('https://example.com/watch?v=M7lc1UVf-VE')
